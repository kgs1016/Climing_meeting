-- ═══════════════════════════════════════════════════════════════
--  이미 지급된 잔액을 새 단위로 옮긴다 (1/100)
-- ═══════════════════════════════════════════════════════════════
-- 20260815195206_credit_rescale.sql 은 "앞으로 얼마를 줄지" 규칙만 바꿨다.
-- 이미 원장에 쌓인 금액은 옛 단위 그대로라, 가입 보너스로 3,000 을 받은
-- 사람은 새 단위에서 관심 300회분을 들고 있다. 여기서 한 번 맞춘다.
--
--   3,000  → 30   (가입 보너스 = 관심 3회, 원래 의도한 값)
--   10,000 → 100  (선착순 = 관심 10회)
--
-- 차감 자체를 원장 한 줄로 남긴다. 잔액 컬럼을 고치는 게 아니라
-- "언제 왜 줄었는지" 가 내역에 보여야 하기 때문이다.
--
-- ⚠️ 되돌릴 수 없다. 마이그레이션 이력에 남으므로 두 번 실행되지는 않는다.

insert into credit_ledger (user_id, delta, reason, ref)
select user_id,
       -(sum(delta) - round(sum(delta) / 100.0))::int,
       'rescale',
       '20260815195206'
  from credit_ledger
 group by user_id
-- delta 는 0 이 될 수 없다 (테이블 제약). 바뀔 게 없는 사람은 건너뛴다.
having sum(delta) > 0
   and sum(delta) - round(sum(delta) / 100.0) <> 0
on conflict (user_id, reason, ref) do nothing;
