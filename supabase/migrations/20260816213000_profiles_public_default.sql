-- ═══════════════════════════════════════════════════════════════
--  가입자 프로필은 기본으로 공개한다
-- ═══════════════════════════════════════════════════════════════
-- is_public 은 기본값이 false 였다. 프로필을 만들 때 앱이 true 로 올려주긴
-- 했지만, 그 전에 만들어진 프로필이나 중간에 내려간 프로필은 false 로 남아
-- 사람 찾기에서 아무도 안 보이는 일이 생겼다.
--
-- 이 앱에서 프로필은 "사람을 보고 고르는" 목록의 재료다. 공개가 기본이고,
-- 보이기 싫으면 탈퇴한다.
--
-- 사진 조건은 그대로 둔다 (profiles_public_needs_photo). 사진 없는 카드가
-- 섞이면 목록이 무너지고, 프로필 완성 자체가 사진을 요구한다.

alter table profiles alter column is_public set default true;

-- 이미 있는 프로필도 올린다. 사진이 없는 건 제약에 걸리므로 건너뛴다
-- (사진을 채우고 저장하면 그때 공개된다).
update profiles set is_public = true
 where photo is not null and is_public = false;
