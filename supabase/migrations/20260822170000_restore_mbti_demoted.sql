-- 20260822120000 이 "키 또는 MBTI 가 없는 공개 프로필" 을 비공개로 내렸다.
-- 그 뒤 20260822150000 이 MBTI 를 다시 선택으로 풀었지만 제약만 바꿨을 뿐
-- 이미 내려간 행은 그대로 남았다. MBTI 는 선택인데 안 적었다는 이유로
-- 사람 찾기에서 사라진 상태다.
--
-- 되돌려도 되는 근거: 앱에는 프로필을 비공개로 바꾸는 경로가 없다.
-- upsertMyProfileDb 는 언제나 is_public = true 로 저장한다. 즉 지금
-- 비공개인 행은 전부 마이그레이션이 내린 것이다.
-- 20260816213000 도 같은 판단으로 같은 update 를 돌렸다.
--
-- 사진 · 키가 없어서 내려간 행은 그대로 둔다 — 그건 지금도 필수다.

update profiles set is_public = true
 where not is_public
   and photo  is not null
   and height is not null;
